  await page.getByRole('radio', { name: 'D · 自定义', exact: false }).check();
  await page.getByLabel('玩偶没有出现时，是否仍判定违规并提醒？', { exact: true }).fill('只有玩偶出现才判断和提醒，摄像头继续提供画面。');
