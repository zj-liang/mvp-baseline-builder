const read = (page: import('@playwright/test').Page): Promise<Project> => page.evaluate(async () => (await fetch('/api/projects/' + localStorage.getItem('active-project'))).json());
test('multi-item list survives failed relationship review without offering placeholder C/D, then retries', async ({ page }) => {
  const old = await initial(page);
  await page.getByRole('button', { name: '加入新功能', exact: true }).click();
  await page.getByLabel('新功能设想', { exact: true }).fill('巡查＋结算＋抓拍');
  await page.getByRole('button', { name: '保存新功能并开始' }).click();
  await expect(page.getByRole('region', { name: '功能归属建议' }).locator('li')).toHaveCount(3);
  await page.route('**/integration/analyze', route => route.fulfill({ status: 502, json: { error: { code: 'invalid_analysis', message: 'AI 返回的结构不符合审查要求，未应用结果，请重试。' } } }));
  await page.getByRole('button', { name: '确认新增清单，审查新旧关系' }).click();
  await expect(page.getByRole('alert')).toContainText('未应用结果');
  await expect(page.getByRole('heading', { name: '新旧功能确认', exact: true })).toBeVisible();
  await expect(page.getByRole('radio')).toHaveCount(0);
  const failed = await read(page); expect(failed.draft.candidates.map(c => c.id)).toEqual(['P0-1','P0-2','P0-3']);
  expect(failed.baseline).toEqual(old.baseline);
  await page.reload(); await expect(page.getByRole('heading', { name: '新旧功能确认', exact: true })).toBeVisible();
  await expect(page.getByRole('radio')).toHaveCount(0);
  await page.unroute('**/integration/analyze');
  await page.getByRole('button', { name: '重新审查新旧关系' }).click();
  await page.getByRole('radio', { name: 'A · 方案一', exact: false }).check();
  await page.getByRole('button', { name: '查看所选决定' }).click();
  await page.getByRole('button', { name: '确认所选决定并接受解决规则', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'MVP 梳理', exact: true })).toBeVisible();
  await expect(page.locator('.candidate-card')).toHaveCount(3);
  await page.getByRole('button', { name: '进入最终确认' }).click();
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: '确认并生成 Baseline v2' }).click();
  expect((await read(page)).baseline!.p0Items.map(c => c.name)).toEqual(['在场监督','结算','抓拍']);
});
async function initial(page: import('@playwright/test').Page, name = '新增功能浏览器') {
  await page.goto('/');
  await page.evaluate(async name => {
    let p = await (await fetch('/api/projects', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ name, productDescription: '监督产品', coreUserGoal: '专注监督', productConcept: '屏幕监督', features: ['在场监督'] }) })).json();
    p = await (await fetch(`/api/projects/${p.id}/analyze`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ revision: p.revision }) })).json();
    p = await (await fetch(`/api/projects/${p.id}/commit`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ revision: p.revision, confirmation: '这就是我希望实现的第一版 MVP 产品逻辑。' }) })).json();
    localStorage.setItem('active-project', p.id);
  }, name);
  await page.reload(); return read(page);
}

